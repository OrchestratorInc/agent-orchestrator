#!/usr/bin/env node
// Renders desktop's file-type icons (@react-symbols/icons, the VS Code "Symbols"
// theme the renderer uses in WorkspaceEntryIcon) to SVG strings for the mobile
// app, which draws them with react-native-svg. Desktop and mobile then show the
// same logo for the same file.
//
// Run from the repo with the frontend installed:
//   node packages/mobile/scripts/generate-file-icons.mjs
// It rewrites packages/mobile/lib/files/fileTypeIcons.generated.ts.

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = join(here, "../../../frontend");
const require = createRequire(join(frontend, "package.json"));
const { createElement } = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const { FileIcon, FolderIcon } = await import(pathToFileURL(join(frontend, "node_modules/@react-symbols/icons/build/utils/index.mjs")).href);

/** Whole file names with an icon of their own. Matched case-insensitively. */
const NAMES = [
	"package.json", "package-lock.json", "tsconfig.json", "jsconfig.json", "dockerfile", "docker-compose.yml", "makefile",
	".gitignore", ".gitattributes", ".env", ".env.local", ".npmrc", ".nvmrc", ".prettierrc", ".editorconfig", "readme.md",
	"license", "changelog.md", "go.mod", "go.sum", "cargo.toml", "cargo.lock", "yarn.lock", "pnpm-lock.yaml", "bun.lockb",
	"vite.config.ts", "vitest.config.ts", "eslint.config.js", "babel.config.js", "metro.config.js", "tailwind.config.js",
	"app.json", "eas.json", "podfile", "gemfile", "requirements.txt", "pyproject.toml", "claude.md", "agents.md", "flake.nix",
];
/** Two-part extensions that read differently from their last part. */
const COMPOUND = ["test.ts", "test.tsx", "test.js", "spec.ts", "spec.tsx", "spec.js", "d.ts", "config.ts", "config.js", "stories.tsx"];
const EXTENSIONS = [
	"ts", "tsx", "js", "jsx", "mjs", "cjs", "json", "jsonc", "md", "mdx", "py", "pyi", "ipynb", "go", "rs", "swift", "kt", "kts",
	"java", "rb", "php", "c", "h", "cc", "cpp", "hpp", "cs", "m", "mm", "css", "scss", "sass", "less", "html", "htm", "vue",
	"svelte", "astro", "yml", "yaml", "toml", "ini", "xml", "plist", "sql", "sh", "bash", "zsh", "fish", "ps1", "lua", "dart",
	"r", "scala", "ex", "exs", "erl", "hs", "ml", "clj", "zig", "nim", "sol", "graphql", "gql", "proto", "tf", "hcl", "nix",
	"lock", "txt", "log", "csv", "pdf", "svg", "png", "jpg", "jpeg", "gif", "webp", "ico", "mp4", "mov", "mp3", "wav", "zip",
	"gz", "tar", "wasm", "prisma", "env", "gradle", "pbxproj", "entitlements", "patch", "diff",
];
const FOLDERS = ["src", "app", "lib", "test", "tests", "docs", "scripts", "assets", "components", "node_modules", ".github", "public", "packages", "backend", "frontend", "ios", "android"];

const svgs = [];
const indexOf = new Map();
const add = (svg) => {
	if (!indexOf.has(svg)) { indexOf.set(svg, svgs.length); svgs.push(svg); }
	return indexOf.get(svg);
};
const file = (fileName) => renderToStaticMarkup(createElement(FileIcon, { fileName, autoAssign: true }));
const folder = (folderName) => renderToStaticMarkup(createElement(FolderIcon, { folderName }));

const fallback = add(file("unknown.unknown-extension"));
const byName = {};
for (const name of NAMES) {
	const index = add(file(name));
	if (index !== fallback) byName[name] = index;
}
const byExtension = {};
for (const extension of [...COMPOUND, ...EXTENSIONS]) {
	const index = add(file(`file.${extension}`));
	if (index !== fallback) byExtension[extension] = index;
}
const folderFallback = add(folder("unknown-folder-name"));
const byFolder = {};
for (const name of FOLDERS) {
	const index = add(folder(name));
	if (index !== folderFallback) byFolder[name] = index;
}

const out = `// GENERATED by packages/mobile/scripts/generate-file-icons.mjs — do not edit by hand.
// File-type icons from @react-symbols/icons (MIT), the set the desktop renderer
// uses, rendered to SVG so mobile shows the same logo for the same file.

export const FILE_ICON_SVGS: readonly string[] = ${JSON.stringify(svgs, null, "\t")};

export const FILE_ICON_FALLBACK = ${fallback};
export const FOLDER_ICON_FALLBACK = ${folderFallback};
export const FILE_ICON_BY_NAME: Readonly<Record<string, number>> = ${JSON.stringify(byName)};
export const FILE_ICON_BY_EXTENSION: Readonly<Record<string, number>> = ${JSON.stringify(byExtension)};
export const FOLDER_ICON_BY_NAME: Readonly<Record<string, number>> = ${JSON.stringify(byFolder)};
`;
const target = join(here, "../lib/files/fileTypeIcons.generated.ts");
writeFileSync(target, out);
console.log(`wrote ${svgs.length} icons (${Math.round(out.length / 1024)} KB) to ${target}`);
