#!/usr/bin/env node
// Regenerates src/api/route-templates.generated.ts from the generated OpenAPI
// types in src/api/schema.ts.
//
// api-client.ts reports telemetry operations as a route template, never a path,
// because project and automation IDs are user-chosen strings that no segment
// heuristic can tell apart from a route word. That list was hand-maintained and
// silently rotted: it held 102 of the schema's 273 routes, so 52 routes leaked
// an identifier into telemetry (POST /api/v1/task-preparations/<token>) and 4
// static routes were attributed to a different operation
// (POST /api/v1/orchestrators/delegate reported as POST /api/v1/orchestrators/:id).
//
// Deriving the list from the schema makes the next route addition show up here
// instead of leaking. `npm run api` runs this after api:ts, and CI regenerates
// and diffs the result, so a stale file fails the build rather than telemetry.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const frontend = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Path keys of the generated `export interface paths { ... }` block. */
function schemaRoutes(schemaSource) {
	const start = schemaSource.indexOf("export interface paths {");
	if (start < 0) throw new Error("schema.ts has no `export interface paths` block");
	const end = schemaSource.indexOf("\n}\n", start);
	if (end < 0) throw new Error("schema.ts `paths` interface is not terminated");
	const block = schemaSource.slice(start, end);
	// Every path key sits at four-space indent and starts with a slash; the
	// nested per-route members (parameters, query, path) never match this.
	const routes = [...block.matchAll(/^ {4}"(\/[^"]*)": \{$/gm)].map((match) => match[1]);
	if (routes.length === 0) throw new Error("schema.ts `paths` block has no routes");
	return [...new Set(routes)].sort();
}

const routes = schemaRoutes(readFileSync(join(frontend, "src/api/schema.ts"), "utf8"));
const file = join(frontend, "src/api/route-templates.generated.ts");

const contents = `// Generated by scripts/api-route-templates.mjs from src/api/schema.ts. Do not edit.
//
// The route templates telemetry reports, one per daemon route. api-client.test.ts
// fails when this file drifts from the schema; run \`npm run api\` from the repo
// root (or \`node scripts/api-route-templates.mjs\` from frontend/) to fix it.
export const ROUTE_TEMPLATES = [
${routes.map((route) => `\t${JSON.stringify(route)},`).join("\n")}
] as const;
`;

writeFileSync(file, contents);
console.log(`Wrote ${routes.length} route templates to ${file}`);
